#!/usr/bin/env python3
"""
Clear media from Immich that was generated by Memoria.

This standalone script identifies assets created by Memoria and can:
- List all matching assets (by album name or filename pattern)
- PERMANENTLY DELETE assets from Immich (removes from library entirely)
- Optionally delete the empty albums themselves

Matching modes:
1. Album-based (default): Match albums with pattern {Platform}/{username}[/{service}]
2. Filename-based (--by-filename): Match files with Memoria filename prefixes

Filename format: {platform}-{username}[-{service}]-{YYYYMMDD}[_seq].ext

Platform prefixes:
    google-      Google (Photos, Chat, Voice)
    discord-     Discord
    insta-       Instagram (Public Media, Messages)
    snap-        Snapchat (Memories, Messages)
    imessage-    iMessage

Filter keys for --prefix:
    google, google-photos, google-chat, google-voice
    discord
    insta, insta-public, insta-msgs
    snap, snap-memories, snap-msgs
    imessage

Usage:
    # List matching albums (dry-run, default)
    python standalone/clear_immich_albums.py

    # List matching files by filename pattern
    python standalone/clear_immich_albums.py --by-filename

    # PERMANENTLY DELETE assets matching filename patterns
    python standalone/clear_immich_albums.py --by-filename --delete

    # Filter by prefix (filename mode only)
    python standalone/clear_immich_albums.py --by-filename --prefix google-photos --delete

    # Use custom credentials
    python standalone/clear_immich_albums.py --url https://immich.local/api --key YOUR_KEY
"""

import argparse
import os
import re
import sys
from pathlib import Path
from typing import Optional

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

try:
    import requests
except ImportError:
    print("Error: 'requests' library is required. Install with: pip install requests")
    sys.exit(1)

# Load .env file if available
try:
    from dotenv import load_dotenv

    load_dotenv(Path(__file__).resolve().parent.parent / ".env")
except ImportError:
    pass  # dotenv is optional


# Known platforms that Memoria creates albums for
KNOWN_PLATFORMS = {"Discord", "Google", "Instagram", "Snapchat", "iMessage"}

# Filename patterns used by Memoria processors
# Format: {platform}-{username}[-{service}]-{YYYYMMDD}[_seq].ext
#
# Platform prefixes (first component of filename):
#   google-    Google services (Photos, Chat, Voice)
#   discord-   Discord
#   insta-     Instagram services (Public Media, Messages)
#   snap-      Snapchat services (Memories, Messages)
#   imessage-  iMessage
#
# Service suffixes (after username, for multi-service platforms):
#   google:  -photos-, -chat-, -voice-
#   insta:   -posts-, -reels-, -stories-, -archived_posts-, -profile-, -other-, -msgs-
#   snap:    -memories-, -msgs-

# Maps filter key to (description, platform, service_pattern)
# service_pattern is a regex pattern to match after the username, or None for any
FILENAME_FILTERS = {
    # Google services
    "google": ("Google (all)", "google", None),
    "google-photos": ("Google Photos", "google", r"-photos-"),
    "google-chat": ("Google Chat", "google", r"-chat-"),
    "google-voice": ("Google Voice", "google", r"-voice-"),
    # Discord (no service variants)
    "discord": ("Discord", "discord", None),
    # Instagram services
    "insta": ("Instagram (all)", "insta", None),
    "insta-public": (
        "Instagram Public Media",
        "insta",
        r"-(posts|reels|stories|archived_posts|profile|other)-",
    ),
    "insta-msgs": ("Instagram Messages", "insta", r"-msgs-"),
    # Snapchat services
    "snap": ("Snapchat (all)", "snap", None),
    "snap-memories": ("Snapchat Memories", "snap", r"-memories-"),
    "snap-msgs": ("Snapchat Messages", "snap", r"-msgs-"),
    # iMessage (no service variants)
    "imessage": ("iMessage", "imessage", None),
}

# All known platform prefixes (for matching any Memoria file)
PLATFORM_PREFIXES = {"google", "discord", "insta", "snap", "imessage"}

# Regex pattern to match any Memoria filename
# Format: {platform}-{username}[-{service}]-{YYYYMMDD}[_seq].ext
MEMORIA_FILENAME_PATTERN = re.compile(
    r"^("
    + "|".join(re.escape(p) for p in sorted(PLATFORM_PREFIXES, key=len, reverse=True))
    + r")-"
)


class ImmichClient:
    """Simple Immich API client for album and asset management."""

    def __init__(self, url: str, api_key: str):
        """Initialize client with server URL and API key.

        Args:
            url: Immich server URL (e.g., https://immich.local or https://immich.local/api)
            api_key: Immich API key
        """
        # Normalize URL - ensure it ends with /api
        url = url.rstrip("/")
        if not url.endswith("/api"):
            url = f"{url}/api"
        self.url = url
        self.headers = {
            "x-api-key": api_key,
            "Content-Type": "application/json",
        }

    def verify_connection(self) -> tuple[bool, Optional[str]]:
        """Verify connection to Immich server.

        Returns:
            Tuple of (success, error_message)
        """
        try:
            # Use /albums endpoint for verification - it requires auth and confirms API access
            response = requests.get(
                f"{self.url}/albums",
                headers=self.headers,
                timeout=10,
            )
            if response.status_code == 200:
                return True, None
            elif response.status_code == 401:
                return False, "Authentication failed - check your API key"
            else:
                return False, f"Server returned status {response.status_code}"
        except requests.ConnectionError:
            return False, "Could not connect to server - check URL"
        except requests.Timeout:
            return False, "Connection timed out"
        except requests.RequestException as e:
            return False, str(e)

    def get_albums(self) -> list[dict]:
        """Get all albums from Immich.

        Returns:
            List of album dictionaries with id, albumName, assetCount, etc.
        """
        response = requests.get(
            f"{self.url}/albums",
            headers=self.headers,
            timeout=30,
        )
        response.raise_for_status()
        return response.json()

    def get_album_assets(self, album_id: str) -> list[str]:
        """Get all asset IDs in an album.

        Args:
            album_id: Album UUID

        Returns:
            List of asset IDs
        """
        response = requests.get(
            f"{self.url}/albums/{album_id}",
            headers=self.headers,
            timeout=30,
        )
        response.raise_for_status()
        album_data = response.json()
        return [asset["id"] for asset in album_data.get("assets", [])]

    def get_all_assets(self, page_size: int = 1000, quiet: bool = False) -> list[dict]:
        """Get all assets from Immich using search/metadata endpoint.

        Args:
            page_size: Number of assets per page
            quiet: Suppress progress output

        Returns:
            List of asset dictionaries with id, originalFileName, etc.
        """
        all_assets = []
        page = 1

        while True:
            response = requests.post(
                f"{self.url}/search/metadata",
                headers=self.headers,
                json={
                    "page": page,
                    "size": page_size,
                },
                timeout=120,
            )
            response.raise_for_status()
            data = response.json()

            # Handle different response formats
            # Format 1: {assets: {items: [...], total: N}}
            # Format 2: {items: [...], nextPage: ...}
            if "assets" in data and isinstance(data["assets"], dict):
                assets = data["assets"].get("items", [])
                total = data["assets"].get("total", 0)
                next_page = data["assets"].get("nextPage")
            else:
                assets = data.get("items", [])
                total = data.get("total", 0)
                next_page = data.get("nextPage")

            if not assets:
                break

            all_assets.extend(assets)

            if not quiet:
                if total > 0:
                    print(
                        f"  Fetched {len(all_assets)}/{total} assets (page {page})..."
                    )
                else:
                    print(f"  Fetched {len(all_assets)} assets (page {page})...")

            # Check if we've reached the end
            if next_page is None and len(all_assets) >= total > 0:
                break

            # If nextPage is provided and is a string token, we can't use page numbers
            if next_page is None:
                # No more pages
                if len(assets) < page_size:
                    break
                page += 1
            elif isinstance(next_page, str):
                # nextPage is a cursor token - not supported yet, fall back to page numbers
                if len(assets) < page_size:
                    break
                page += 1
            else:
                page += 1

        return all_assets

    def remove_assets_from_album(self, album_id: str, asset_ids: list[str]) -> dict:
        """Remove assets from an album.

        Note: This only removes assets from the album, not from Immich library.

        Args:
            album_id: Album UUID
            asset_ids: List of asset IDs to remove

        Returns:
            Response data with success/error information
        """
        if not asset_ids:
            return {"success": [], "error": []}

        # Immich API may have batch size limits, process in chunks
        chunk_size = 1000
        all_success = []
        all_errors = []

        for i in range(0, len(asset_ids), chunk_size):
            chunk = asset_ids[i : i + chunk_size]
            response = requests.delete(
                f"{self.url}/albums/{album_id}/assets",
                headers=self.headers,
                json={"ids": chunk},
                timeout=60,
            )
            response.raise_for_status()

            try:
                result = response.json()
                # Response contains list of {id, success, error} objects
                for item in result:
                    if item.get("success", False):
                        all_success.append(item.get("id"))
                    else:
                        all_errors.append(item.get("id"))
            except (ValueError, TypeError):
                # Fallback if response format differs
                all_success.extend(chunk)

        return {"success": all_success, "error": all_errors}

    def delete_album(self, album_id: str) -> bool:
        """Delete an album.

        Note: This only deletes the album, not the assets.

        Args:
            album_id: Album UUID

        Returns:
            True if successful
        """
        response = requests.delete(
            f"{self.url}/albums/{album_id}",
            headers=self.headers,
            timeout=30,
        )
        response.raise_for_status()
        return True

    def delete_assets(self, asset_ids: list[str], force: bool = True) -> dict:
        """Permanently delete assets from Immich.

        WARNING: This permanently deletes assets from the Immich library.
        With force=True, assets are deleted immediately without going to trash.

        Args:
            asset_ids: List of asset IDs to delete
            force: If True, permanently delete without trash (default: True)

        Returns:
            Response data with success/error information
        """
        if not asset_ids:
            return {"success": 0, "error": 0}

        # Process in chunks to avoid API limits
        chunk_size = 1000
        total_deleted = 0
        total_errors = 0

        for i in range(0, len(asset_ids), chunk_size):
            chunk = asset_ids[i : i + chunk_size]
            response = requests.delete(
                f"{self.url}/assets",
                headers=self.headers,
                json={"ids": chunk, "force": force},
                timeout=120,
            )
            response.raise_for_status()
            total_deleted += len(chunk)

        return {"success": total_deleted, "error": total_errors}


def is_memoria_album(album_name: str, platform_filter: Optional[str] = None) -> bool:
    """Check if an album was created by Memoria.

    Args:
        album_name: Album name to check
        platform_filter: Optional platform to filter by (e.g., "Google")

    Returns:
        True if album matches Memoria naming pattern
    """
    if not album_name:
        return False

    parts = album_name.split("/")
    if len(parts) < 2:
        return False

    platform = parts[0]

    if platform not in KNOWN_PLATFORMS:
        return False

    if platform_filter and platform != platform_filter:
        return False

    return True


def is_memoria_filename(filename: str, filter_key: Optional[str] = None) -> bool:
    """Check if a filename matches Memoria naming conventions.

    Args:
        filename: Filename to check (without path)
        filter_key: Optional filter key (e.g., "google-photos", "discord")

    Returns:
        True if filename matches Memoria pattern
    """
    if not filename:
        return False

    if filter_key:
        if filter_key not in FILENAME_FILTERS:
            return False
        _desc, platform, service_pattern = FILENAME_FILTERS[filter_key]

        # Must start with the platform prefix
        if not filename.startswith(f"{platform}-"):
            return False

        # If service pattern specified, must match after username
        if service_pattern:
            # Pattern: {platform}-{username}{service_pattern}{date}
            # Service pattern includes the leading dash
            pattern = re.compile(
                r"^" + re.escape(platform) + r"-[^-]+" + service_pattern
            )
            return bool(pattern.match(filename))

        return True

    return bool(MEMORIA_FILENAME_PATTERN.match(filename))


def get_filename_filter_key(filename: str) -> Optional[str]:
    """Determine which filter key a filename matches.

    Finds the most specific matching filter key for categorization.

    Args:
        filename: Filename to check

    Returns:
        The most specific matching filter key, or None if no match
    """
    match = MEMORIA_FILENAME_PATTERN.match(filename)
    if not match:
        return None

    platform = match.group(1)

    # Try to find a specific service match first
    for key, (_desc, key_platform, service_pattern) in FILENAME_FILTERS.items():
        if key_platform != platform:
            continue
        if service_pattern:
            # Check if service pattern matches
            pattern = re.compile(
                r"^" + re.escape(platform) + r"-[^-]+" + service_pattern
            )
            if pattern.match(filename):
                return key

    # Fall back to platform-only match
    if platform in FILENAME_FILTERS:
        return platform

    return None


def format_album_info(album: dict) -> str:
    """Format album info for display.

    Args:
        album: Album dictionary from Immich API

    Returns:
        Formatted string
    """
    name = album.get("albumName", "Unknown")
    count = album.get("assetCount", 0)
    return f"  {name} ({count} assets)"


def run_album_mode(client: ImmichClient, args) -> int:
    """Run album-based matching mode.

    Returns:
        Exit code (0 for success, 1 for errors)
    """
    # Get all albums
    try:
        all_albums = client.get_albums()
    except requests.HTTPError as e:
        if e.response is not None and e.response.status_code == 401:
            print("Error: Authentication failed - check your API key")
        else:
            print(f"Error fetching albums: {e}")
        return 1
    except requests.RequestException as e:
        print(f"Error fetching albums: {e}")
        return 1

    # Filter to Memoria albums
    memoria_albums = [
        album
        for album in all_albums
        if is_memoria_album(album.get("albumName", ""), args.platform)
    ]

    if not memoria_albums:
        platform_msg = f" for platform '{args.platform}'" if args.platform else ""
        print(f"No Memoria albums found{platform_msg}.")
        return 0

    # Display matching albums
    total_assets = sum(album.get("assetCount", 0) for album in memoria_albums)
    platform_msg = f" ({args.platform})" if args.platform else ""
    print(f"Found {len(memoria_albums)} Memoria album(s){platform_msg}:")
    print(f"Total assets: {total_assets}\n")

    for album in sorted(memoria_albums, key=lambda a: a.get("albumName", "")):
        print(format_album_info(album))

    print()

    # If just listing (dry-run), exit here
    if not args.delete:
        print("Dry-run mode. Use --delete to PERMANENTLY DELETE assets from Immich.")
        return 0

    # Confirm action
    if not args.yes:
        print("WARNING: This will PERMANENTLY DELETE all assets from these albums!")
        print("         Assets will be removed from Immich entirely, not just albums.")
        print("         This action CANNOT be undone.\n")

        action = "PERMANENTLY DELETE assets from"
        if args.delete_albums:
            action = "PERMANENTLY DELETE assets from and delete"

        confirm = input(
            f"Are you sure you want to {action} {len(memoria_albums)} album(s) "
            f"({total_assets} assets)? [y/N]: "
        )
        if confirm.lower() not in ("y", "yes"):
            print("Aborted.")
            return 0

    print()

    # Process each album
    success_count = 0
    error_count = 0

    for album in sorted(memoria_albums, key=lambda a: a.get("albumName", "")):
        album_id = album["id"]
        album_name = album.get("albumName", "Unknown")
        asset_count = album.get("assetCount", 0)

        if not args.quiet:
            print(f"Processing: {album_name}")

        try:
            # Get asset IDs and delete
            if asset_count > 0:
                asset_ids = client.get_album_assets(album_id)

                if asset_ids:
                    result = client.delete_assets(asset_ids)
                    deleted = result.get("success", 0)
                    errors = result.get("error", 0)

                    if not args.quiet:
                        print(f"  Permanently deleted {deleted} assets")
                        if errors:
                            print(f"  Failed to delete {errors} assets")

            # Delete album if requested
            if args.delete_albums:
                client.delete_album(album_id)
                if not args.quiet:
                    print("  Deleted album")

            success_count += 1

        except requests.RequestException as e:
            print(f"  Error: {e}")
            error_count += 1

    print()
    print(f"Completed: {success_count} album(s) processed, {error_count} error(s)")

    return 0 if error_count == 0 else 1


def run_filename_mode(client: ImmichClient, args) -> int:
    """Run filename-based matching mode.

    Returns:
        Exit code (0 for success, 1 for errors)
    """
    if not args.quiet:
        print("Fetching all assets from Immich (this may take a while)...")

    try:
        all_assets = client.get_all_assets(quiet=args.quiet)
    except requests.HTTPError as e:
        if e.response is not None and e.response.status_code == 401:
            print("Error: Authentication failed - check your API key")
        else:
            print(f"Error fetching assets: {e}")
        return 1
    except requests.RequestException as e:
        print(f"Error fetching assets: {e}")
        return 1

    if not args.quiet:
        print(f"Found {len(all_assets)} total assets in Immich.\n")

    # Filter to Memoria assets by filename
    matching_assets = []
    filter_counts: dict[str, int] = {}

    for asset in all_assets:
        filename = asset.get("originalFileName", "")
        if is_memoria_filename(filename, args.prefix):
            matching_assets.append(asset)
            filter_key = get_filename_filter_key(filename)
            if filter_key:
                filter_counts[filter_key] = filter_counts.get(filter_key, 0) + 1

    if not matching_assets:
        prefix_msg = f" with filter '{args.prefix}'" if args.prefix else ""
        print(f"No Memoria assets found{prefix_msg}.")
        return 0

    # Display summary
    prefix_msg = f" (filter: {args.prefix})" if args.prefix else ""
    print(f"Found {len(matching_assets)} Memoria asset(s){prefix_msg}:\n")

    # Show breakdown by filter key
    for filter_key in sorted(filter_counts.keys()):
        count = filter_counts[filter_key]
        description = FILENAME_FILTERS.get(filter_key, ("Unknown",))[0]
        print(f"  {filter_key}: {count} assets ({description})")

    print()

    # If just listing (dry-run), exit here
    if not args.delete:
        print(
            "Dry-run mode. Use --delete to PERMANENTLY DELETE these assets from Immich."
        )
        return 0

    # Confirm action
    if not args.yes:
        print("WARNING: This will PERMANENTLY DELETE all matching assets!")
        print("         Assets will be removed from Immich entirely.")
        print("         This action CANNOT be undone.\n")

        confirm = input(
            f"Are you sure you want to PERMANENTLY DELETE {len(matching_assets)} assets? [y/N]: "
        )
        if confirm.lower() not in ("y", "yes"):
            print("Aborted.")
            return 0

    print()

    # Delete assets
    if not args.quiet:
        print(f"Deleting {len(matching_assets)} assets...")

    asset_ids = [asset["id"] for asset in matching_assets]

    try:
        result = client.delete_assets(asset_ids)
        deleted = result.get("success", 0)
        errors = result.get("error", 0)

        print(f"\nCompleted: {deleted} assets deleted")
        if errors:
            print(f"           {errors} errors")
            return 1

    except requests.RequestException as e:
        print(f"Error deleting assets: {e}")
        return 1

    return 0


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Clear media from Immich that was generated by Memoria.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    # List matching albums (dry-run, default)
    python standalone/clear_immich_albums.py

    # List matching files by filename pattern
    python standalone/clear_immich_albums.py --by-filename

    # PERMANENTLY DELETE assets matching filename patterns
    python standalone/clear_immich_albums.py --by-filename --delete

    # Filter by prefix (filename mode)
    python standalone/clear_immich_albums.py --by-filename --prefix google-photos --delete

    # Filter by platform (album mode)
    python standalone/clear_immich_albums.py --platform Google --delete

Filename format: {platform}-{username}[-{service}]-{YYYYMMDD}[_seq].ext

Filter keys for --prefix:
    google           Google (all services)
    google-photos    Google Photos
    google-chat      Google Chat
    google-voice     Google Voice
    discord          Discord
    insta            Instagram (all services)
    insta-public     Instagram Public Media (posts, reels, stories, etc.)
    insta-msgs       Instagram Messages
    snap             Snapchat (all services)
    snap-memories    Snapchat Memories
    snap-msgs        Snapchat Messages
    imessage         iMessage

Environment Variables:
    IMMICH_INSTANCE_URL    Immich server URL
    IMMICH_API_KEY         Immich API key
        """,
    )

    parser.add_argument(
        "--url",
        dest="immich_url",
        default=os.environ.get("IMMICH_INSTANCE_URL", ""),
        help="Immich server URL (default: from IMMICH_INSTANCE_URL env var)",
    )
    parser.add_argument(
        "--key",
        dest="immich_key",
        default=os.environ.get("IMMICH_API_KEY", ""),
        help="Immich API key (default: from IMMICH_API_KEY env var)",
    )

    # Matching mode
    parser.add_argument(
        "--by-filename",
        action="store_true",
        help="Match assets by filename pattern instead of album membership",
    )

    # Filters (mutually exclusive based on mode)
    parser.add_argument(
        "--platform",
        choices=sorted(KNOWN_PLATFORMS),
        help="Filter albums by platform (album mode only)",
    )
    parser.add_argument(
        "--prefix",
        choices=sorted(FILENAME_FILTERS.keys()),
        help="Filter by filename pattern (filename mode only)",
    )

    # Actions
    parser.add_argument(
        "--delete",
        action="store_true",
        help="PERMANENTLY DELETE matching assets from Immich library (irreversible!)",
    )
    parser.add_argument(
        "--delete-albums",
        action="store_true",
        help="Also delete albums after deleting assets (album mode only)",
    )
    parser.add_argument(
        "--yes",
        "-y",
        action="store_true",
        help="Skip confirmation prompts",
    )
    parser.add_argument(
        "--quiet",
        "-q",
        action="store_true",
        help="Suppress progress output",
    )

    args = parser.parse_args()

    # Validate arguments
    if args.by_filename and args.platform:
        parser.error("--platform is only valid in album mode (without --by-filename)")

    if not args.by_filename and args.prefix:
        parser.error("--prefix requires --by-filename mode")

    if args.delete_albums and args.by_filename:
        parser.error(
            "--delete-albums is only valid in album mode (without --by-filename)"
        )

    if args.delete_albums and not args.delete:
        parser.error("--delete-albums requires --delete")

    if not args.immich_url:
        print("Error: Immich URL not provided.")
        print("Set IMMICH_INSTANCE_URL environment variable or use --url")
        sys.exit(1)

    if not args.immich_key:
        print("Error: Immich API key not provided.")
        print("Set IMMICH_API_KEY environment variable or use --key")
        sys.exit(1)

    # Create client and verify connection
    client = ImmichClient(args.immich_url, args.immich_key)

    if not args.quiet:
        print(f"Connecting to Immich at {client.url}...")

    connected, error = client.verify_connection()
    if not connected:
        print(f"Error: {error}")
        print("Please verify your URL and API key.")
        sys.exit(1)

    if not args.quiet:
        print("Connected successfully.\n")

    # Run appropriate mode
    if args.by_filename:
        exit_code = run_filename_mode(client, args)
    else:
        exit_code = run_album_mode(client, args)

    sys.exit(exit_code)


if __name__ == "__main__":
    main()
