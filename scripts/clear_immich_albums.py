#!/usr/bin/env python3
"""
Clear media from Immich albums generated by Memoria.

This standalone script identifies albums created by Memoria and can:
- List all matching albums and their asset counts
- Remove all assets from those albums (assets remain in Immich library)
- PERMANENTLY DELETE assets from Immich (removes from library entirely)
- Optionally delete the empty albums themselves

Album naming pattern used by Memoria:
    {Platform}/{username}[/{service}]

Known platforms: Discord, Google, Instagram, Snapchat, iMessage

Usage:
    # List matching albums (dry-run, default)
    python scripts/clear_immich_albums.py

    # Remove assets from albums only (assets stay in library)
    python scripts/clear_immich_albums.py --remove-assets

    # PERMANENTLY DELETE assets from Immich (irreversible!)
    python scripts/clear_immich_albums.py --delete-assets

    # Delete assets and remove empty albums
    python scripts/clear_immich_albums.py --delete-assets --delete-albums

    # Filter by platform
    python scripts/clear_immich_albums.py --platform Google --delete-assets

    # Use custom credentials
    python scripts/clear_immich_albums.py --url https://immich.local/api --key YOUR_KEY
"""

import argparse
import os
import sys
from pathlib import Path
from typing import Optional

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

try:
    import requests
except ImportError:
    print("Error: 'requests' library is required. Install with: pip install requests")
    sys.exit(1)

# Load .env file if available
try:
    from dotenv import load_dotenv

    load_dotenv(Path(__file__).resolve().parent.parent / ".env")
except ImportError:
    pass  # dotenv is optional


# Known platforms that Memoria creates albums for
KNOWN_PLATFORMS = {"Discord", "Google", "Instagram", "Snapchat", "iMessage"}

# Album structure reference:
# Discord/{username}
# Google/{username}/photos
# Google/{username}/chat
# Google/{username}/voice
# iMessage/{device}
# Instagram/{username}/messages
# Instagram/{username}/posts
# Instagram/{username}/stories
# Instagram/{username}/reels
# Instagram/{username}/archived_posts
# Instagram/{username}/profile
# Instagram/{username}/other
# Snapchat/{username}/memories
# Snapchat/{username}/messages


class ImmichClient:
    """Simple Immich API client for album management."""

    def __init__(self, url: str, api_key: str):
        """Initialize client with server URL and API key.

        Args:
            url: Immich server URL (e.g., https://immich.local or https://immich.local/api)
            api_key: Immich API key
        """
        # Normalize URL - ensure it ends with /api
        url = url.rstrip("/")
        if not url.endswith("/api"):
            url = f"{url}/api"
        self.url = url
        self.headers = {
            "x-api-key": api_key,
            "Content-Type": "application/json",
        }

    def verify_connection(self) -> tuple[bool, Optional[str]]:
        """Verify connection to Immich server.

        Returns:
            Tuple of (success, error_message)
        """
        try:
            # Use /albums endpoint for verification - it requires auth and confirms API access
            response = requests.get(
                f"{self.url}/albums",
                headers=self.headers,
                timeout=10,
            )
            if response.status_code == 200:
                return True, None
            elif response.status_code == 401:
                return False, "Authentication failed - check your API key"
            else:
                return False, f"Server returned status {response.status_code}"
        except requests.ConnectionError:
            return False, "Could not connect to server - check URL"
        except requests.Timeout:
            return False, "Connection timed out"
        except requests.RequestException as e:
            return False, str(e)

    def get_albums(self) -> list[dict]:
        """Get all albums from Immich.

        Returns:
            List of album dictionaries with id, albumName, assetCount, etc.
        """
        response = requests.get(
            f"{self.url}/albums",
            headers=self.headers,
            timeout=30,
        )
        response.raise_for_status()
        return response.json()

    def get_album_assets(self, album_id: str) -> list[str]:
        """Get all asset IDs in an album.

        Args:
            album_id: Album UUID

        Returns:
            List of asset IDs
        """
        response = requests.get(
            f"{self.url}/albums/{album_id}",
            headers=self.headers,
            timeout=30,
        )
        response.raise_for_status()
        album_data = response.json()
        return [asset["id"] for asset in album_data.get("assets", [])]

    def remove_assets_from_album(self, album_id: str, asset_ids: list[str]) -> dict:
        """Remove assets from an album.

        Note: This only removes assets from the album, not from Immich library.

        Args:
            album_id: Album UUID
            asset_ids: List of asset IDs to remove

        Returns:
            Response data with success/error information
        """
        if not asset_ids:
            return {"success": [], "error": []}

        # Immich API may have batch size limits, process in chunks
        chunk_size = 1000
        all_success = []
        all_errors = []

        for i in range(0, len(asset_ids), chunk_size):
            chunk = asset_ids[i : i + chunk_size]
            response = requests.delete(
                f"{self.url}/albums/{album_id}/assets",
                headers=self.headers,
                json={"ids": chunk},
                timeout=60,
            )
            response.raise_for_status()
            
            try:
                result = response.json()
                # Response contains list of {id, success, error} objects
                for item in result:
                    if item.get("success", False):
                        all_success.append(item.get("id"))
                    else:
                        all_errors.append(item.get("id"))
            except (ValueError, TypeError):
                # Fallback if response format differs
                all_success.extend(chunk)

        return {"success": all_success, "error": all_errors}

    def delete_album(self, album_id: str) -> bool:
        """Delete an album.

        Note: This only deletes the album, not the assets.

        Args:
            album_id: Album UUID

        Returns:
            True if successful
        """
        response = requests.delete(
            f"{self.url}/albums/{album_id}",
            headers=self.headers,
            timeout=30,
        )
        response.raise_for_status()
        return True

    def delete_assets(self, asset_ids: list[str], force: bool = True) -> dict:
        """Permanently delete assets from Immich.

        WARNING: This permanently deletes assets from the Immich library.
        With force=True, assets are deleted immediately without going to trash.

        Args:
            asset_ids: List of asset IDs to delete
            force: If True, permanently delete without trash (default: True)

        Returns:
            Response data with success/error information
        """
        if not asset_ids:
            return {"success": 0, "error": 0}

        # Process in chunks to avoid API limits
        chunk_size = 1000
        total_deleted = 0
        total_errors = 0

        for i in range(0, len(asset_ids), chunk_size):
            chunk = asset_ids[i : i + chunk_size]
            response = requests.delete(
                f"{self.url}/assets",
                headers=self.headers,
                json={"ids": chunk, "force": force},
                timeout=120,
            )
            response.raise_for_status()
            total_deleted += len(chunk)

        return {"success": total_deleted, "error": total_errors}


def is_memoria_album(album_name: str, platform_filter: Optional[str] = None) -> bool:
    """Check if an album was created by Memoria.

    Args:
        album_name: Album name to check
        platform_filter: Optional platform to filter by (e.g., "Google")

    Returns:
        True if album matches Memoria naming pattern
    """
    if not album_name:
        return False

    parts = album_name.split("/")
    if len(parts) < 2:
        return False

    platform = parts[0]

    if platform not in KNOWN_PLATFORMS:
        return False

    if platform_filter and platform != platform_filter:
        return False

    return True


def format_album_info(album: dict) -> str:
    """Format album info for display.

    Args:
        album: Album dictionary from Immich API

    Returns:
        Formatted string
    """
    name = album.get("albumName", "Unknown")
    count = album.get("assetCount", 0)
    return f"  {name} ({count} assets)"


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Clear media from Immich albums generated by Memoria.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    # List matching albums (dry-run, default)
    python scripts/clear_immich_albums.py

    # Remove assets from albums only (assets stay in library)
    python scripts/clear_immich_albums.py --remove-assets

    # PERMANENTLY DELETE assets from Immich (irreversible!)
    python scripts/clear_immich_albums.py --delete-assets

    # Delete assets and remove empty albums
    python scripts/clear_immich_albums.py --delete-assets --delete-albums

    # Filter by platform
    python scripts/clear_immich_albums.py --platform Google --delete-assets

Environment Variables:
    IMMICH_INSTANCE_URL    Immich server URL
    IMMICH_API_KEY         Immich API key
        """,
    )

    parser.add_argument(
        "--url",
        dest="immich_url",
        default=os.environ.get("IMMICH_INSTANCE_URL", ""),
        help="Immich server URL (default: from IMMICH_INSTANCE_URL env var)",
    )
    parser.add_argument(
        "--key",
        dest="immich_key",
        default=os.environ.get("IMMICH_API_KEY", ""),
        help="Immich API key (default: from IMMICH_API_KEY env var)",
    )
    parser.add_argument(
        "--platform",
        choices=sorted(KNOWN_PLATFORMS),
        help="Filter albums by platform (e.g., Google, Instagram)",
    )
    parser.add_argument(
        "--remove-assets",
        action="store_true",
        help="Remove all assets from matching albums (assets stay in Immich library)",
    )
    parser.add_argument(
        "--delete-assets",
        action="store_true",
        help="PERMANENTLY DELETE assets from Immich library (irreversible!)",
    )
    parser.add_argument(
        "--delete-albums",
        action="store_true",
        help="Delete albums after processing (requires --remove-assets or --delete-assets)",
    )
    parser.add_argument(
        "--yes",
        "-y",
        action="store_true",
        help="Skip confirmation prompts",
    )
    parser.add_argument(
        "--quiet",
        "-q",
        action="store_true",
        help="Suppress progress output",
    )

    args = parser.parse_args()

    # Validate arguments
    if args.delete_albums and not (args.remove_assets or args.delete_assets):
        parser.error("--delete-albums requires --remove-assets or --delete-assets")
    
    if args.remove_assets and args.delete_assets:
        parser.error("--remove-assets and --delete-assets are mutually exclusive")

    if not args.immich_url:
        print("Error: Immich URL not provided.")
        print("Set IMMICH_INSTANCE_URL environment variable or use --url")
        sys.exit(1)

    if not args.immich_key:
        print("Error: Immich API key not provided.")
        print("Set IMMICH_API_KEY environment variable or use --key")
        sys.exit(1)

    # Create client and verify connection
    client = ImmichClient(args.immich_url, args.immich_key)

    if not args.quiet:
        print(f"Connecting to Immich at {client.url}...")

    connected, error = client.verify_connection()
    if not connected:
        print(f"Error: {error}")
        print("Please verify your URL and API key.")
        sys.exit(1)

    if not args.quiet:
        print("Connected successfully.\n")

    # Get all albums
    try:
        all_albums = client.get_albums()
    except requests.HTTPError as e:
        if e.response is not None and e.response.status_code == 401:
            print("Error: Authentication failed - check your API key")
        else:
            print(f"Error fetching albums: {e}")
        sys.exit(1)
    except requests.RequestException as e:
        print(f"Error fetching albums: {e}")
        sys.exit(1)

    # Filter to Memoria albums
    memoria_albums = [
        album
        for album in all_albums
        if is_memoria_album(album.get("albumName", ""), args.platform)
    ]

    if not memoria_albums:
        platform_msg = f" for platform '{args.platform}'" if args.platform else ""
        print(f"No Memoria albums found{platform_msg}.")
        sys.exit(0)

    # Display matching albums
    total_assets = sum(album.get("assetCount", 0) for album in memoria_albums)
    platform_msg = f" ({args.platform})" if args.platform else ""
    print(f"Found {len(memoria_albums)} Memoria album(s){platform_msg}:")
    print(f"Total assets: {total_assets}\n")

    for album in sorted(memoria_albums, key=lambda a: a.get("albumName", "")):
        print(format_album_info(album))

    print()

    # If just listing (dry-run), exit here
    if not args.remove_assets and not args.delete_assets:
        print("Dry-run mode.")
        print("  Use --remove-assets to remove assets from albums (keeps assets in library)")
        print("  Use --delete-assets to PERMANENTLY DELETE assets from Immich")
        sys.exit(0)

    # Confirm action with extra warning for permanent deletion
    if not args.yes:
        if args.delete_assets:
            print("WARNING: This will PERMANENTLY DELETE all assets from these albums!")
            print("         Assets will be removed from Immich entirely, not just albums.")
            print("         This action CANNOT be undone.\n")
            action = "PERMANENTLY DELETE"
            if args.delete_albums:
                action = "PERMANENTLY DELETE assets from and delete"
        else:
            action = "remove assets from"
            if args.delete_albums:
                action = "remove assets from and delete"

        confirm = input(
            f"Are you sure you want to {action} {len(memoria_albums)} album(s) "
            f"({total_assets} assets)? [y/N]: "
        )
        if confirm.lower() not in ("y", "yes"):
            print("Aborted.")
            sys.exit(0)

    print()

    # Process each album
    success_count = 0
    error_count = 0

    for album in sorted(memoria_albums, key=lambda a: a.get("albumName", "")):
        album_id = album["id"]
        album_name = album.get("albumName", "Unknown")
        asset_count = album.get("assetCount", 0)

        if not args.quiet:
            print(f"Processing: {album_name}")

        try:
            # Get asset IDs
            if asset_count > 0:
                asset_ids = client.get_album_assets(album_id)

                if asset_ids:
                    if args.delete_assets:
                        # Permanently delete assets from Immich
                        result = client.delete_assets(asset_ids)
                        deleted = result.get("success", 0)
                        errors = result.get("error", 0)

                        if not args.quiet:
                            print(f"  Permanently deleted {deleted} assets")
                            if errors:
                                print(f"  Failed to delete {errors} assets")
                    else:
                        # Just remove assets from album
                        result = client.remove_assets_from_album(album_id, asset_ids)
                        removed = len(result.get("success", []))
                        errors = len(result.get("error", []))

                        if not args.quiet:
                            print(f"  Removed {removed} assets from album")
                            if errors:
                                print(f"  Failed to remove {errors} assets")

            # Delete album if requested
            if args.delete_albums:
                client.delete_album(album_id)
                if not args.quiet:
                    print("  Deleted album")

            success_count += 1

        except requests.RequestException as e:
            print(f"  Error: {e}")
            error_count += 1

    print()
    print(f"Completed: {success_count} album(s) processed, {error_count} error(s)")

    sys.exit(0 if error_count == 0 else 1)


if __name__ == "__main__":
    main()

